def force_expand_abbreviations(text: str) -> str:
    if not text:
        return text

    # Сортируем ключи по длине в обратном порядке, чтобы длинные аббревиатуры (например, ЭХО-КГ)
    # обрабатывались раньше коротких (например, КГ) во избежание частичной замены.
    sorted_abbrs = sorted(MEDICAL_DICT.keys(), key=len, reverse=True)

    for abbr in sorted_abbrs:
        expansion = MEDICAL_DICT[abbr]
        # Регулярное выражение ищет аббревиатуру как отдельное слово (с учетом русских границ слов)
        # Исключаем повторную замену, если скобки с расшифровкой уже есть в тексте
        pattern = rf"(?<!\w){abbr}(?!\w)(?!\s*\({re.escape(expansion)}\))"
        replacement = f"{abbr} ({expansion})"
        text = re.sub(pattern, replacement, text)

    return text