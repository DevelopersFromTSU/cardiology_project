def force_expand_abbreviations(text):
    """
    Принудительно расшифровывает медицинские аббревиатуры в обычном парсенном тексте.
    """
    processed_text = text
    for abbr, expansion in MEDICAL_DICT.items():
        # [МОДИФИЦИРОВАНО]: Оборачиваем чистый ключ в \b динамически при поиске
        pattern = rf'(?<!\()\b{re.escape(abbr)}\b(?!\))'
        processed_text = re.sub(pattern, expansion, processed_text)

    return processed_text